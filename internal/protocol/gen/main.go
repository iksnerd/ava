// Command gen renders internal/protocol/protocol.json into one file per
// runtime. Run it with `make generate-protocol`; `make check-protocol` fails
// when a rendered file is stale.
//
// Generation rather than a file every runtime reads at startup, because the
// runtimes cannot agree on a path that exists: Go's go:embed cannot reach
// outside its own package, an installed ava has no scripts/ beside
// it, and the menu bar app ships only what its bundle was told to carry. A
// file read at runtime would work for two of the four and leave hand-written
// copies for the rest — worse than no generator, because the copies would then
// look authoritative.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type entry struct {
	Value string `json:"value"`
	Doc   string `json:"doc"`
}

const banner = "Generated by internal/protocol/gen from internal/protocol/protocol.json. DO NOT EDIT."

func main() {
	root, err := os.Getwd()
	if err != nil {
		fail(err)
	}
	// Allow running from anywhere inside the repo.
	for {
		if _, err := os.Stat(filepath.Join(root, "go.mod")); err == nil {
			break
		}
		parent := filepath.Dir(root)
		if parent == root {
			fail(fmt.Errorf("no go.mod above %s", root))
		}
		root = parent
	}

	raw, err := os.ReadFile(filepath.Join(root, "internal", "protocol", "protocol.json"))
	if err != nil {
		fail(err)
	}
	var all map[string]json.RawMessage
	if err := json.Unmarshal(raw, &all); err != nil {
		fail(err)
	}

	keys := make([]string, 0, len(all))
	entries := map[string]entry{}
	for k, v := range all {
		if strings.HasPrefix(k, "_") {
			continue
		}
		var e entry
		if err := json.Unmarshal(v, &e); err != nil {
			fail(fmt.Errorf("%s: %w", k, err))
		}
		if e.Value == "" || e.Doc == "" {
			fail(fmt.Errorf("%s: both value and doc are required", k))
		}
		entries[k] = e
		keys = append(keys, k)
	}
	sort.Strings(keys)

	writes := map[string]string{
		filepath.Join("internal", "protocol", "protocol_gen.go"):               renderGo(keys, entries),
		filepath.Join("scripts", "protocol.sh"):                                renderBash(keys, entries),
		filepath.Join("AvaMenuBar", "Sources", "AvaMenuBar", "Protocol.swift"): renderSwift(keys, entries),
		filepath.Join("mlx-engine", "protocol.py"):                             renderPython(keys, entries),
	}

	check := len(os.Args) > 1 && os.Args[1] == "-check"
	stale := []string{}
	for rel, body := range writes {
		path := filepath.Join(root, rel)
		if check {
			old, err := os.ReadFile(path)
			if err != nil || string(old) != body {
				stale = append(stale, rel)
			}
			continue
		}
		if err := os.WriteFile(path, []byte(body), 0644); err != nil {
			fail(err)
		}
		fmt.Println("wrote", rel)
	}

	if check {
		if len(stale) > 0 {
			sort.Strings(stale)
			fmt.Fprintln(os.Stderr, "❌ Generated from protocol.json but stale on disk:")
			for _, s := range stale {
				fmt.Fprintln(os.Stderr, "  "+s)
			}
			fmt.Fprintln(os.Stderr, "\n   Run `make generate-protocol` and commit the result.")
			os.Exit(1)
		}
		fmt.Printf("✅ Protocol constants are current (%d values, %d files)\n", len(keys), len(writes))
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "protocol gen:", err)
	os.Exit(1)
}

// wrap breaks doc text onto comment lines of at most width runes.
func wrap(text, prefix string, width int) string {
	var out, line []string
	n := 0
	for _, w := range strings.Fields(text) {
		if n > 0 && n+1+len(w) > width {
			out = append(out, prefix+strings.Join(line, " "))
			line, n = nil, 0
		}
		line = append(line, w)
		n += len(w) + 1
	}
	if len(line) > 0 {
		out = append(out, prefix+strings.Join(line, " "))
	}
	return strings.Join(out, "\n")
}

func goName(k string) string {
	parts := strings.Split(k, "_")
	for i, p := range parts {
		switch p {
		case "url":
			parts[i] = "URL"
		case "pid":
			parts[i] = "PID"
		case "env":
			parts[i] = "Env"
		default:
			parts[i] = strings.ToUpper(p[:1]) + p[1:]
		}
	}
	return strings.Join(parts, "")
}

func swiftName(k string) string {
	n := goName(k)
	return strings.ToLower(n[:1]) + n[1:]
}

func renderGo(keys []string, e map[string]entry) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\n\npackage protocol\n\nconst (\n", banner)
	for i, k := range keys {
		if i > 0 {
			b.WriteString("\n")
		}
		fmt.Fprintf(&b, "%s\n\t%s = %q\n", wrap(e[k].Doc, "\t// ", 72), goName(k), e[k].Value)
	}
	b.WriteString(")\n")
	return b.String()
}

func renderBash(keys []string, e map[string]entry) string {
	var b strings.Builder
	fmt.Fprintf(&b, "#!/bin/bash\n# %s\n#\n# Sourced by the scripts that speak and stop speaking.\n\n", banner)
	for _, k := range keys {
		fmt.Fprintf(&b, "%s\n%s=%q\n\n", wrap(e[k].Doc, "# ", 76), strings.ToUpper(k), e[k].Value)
	}
	// Trailing blank line trimmed: ruff format rejects it.
	return strings.TrimRight(b.String(), "\n") + "\n"
}

func renderSwift(keys []string, e map[string]entry) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s\n\n// Named AvaProtocol, not Protocol: Protocol is the ObjC bridging type\n// and shadowing it produces errors far from this file.\nenum AvaProtocol {\n", banner)
	for i, k := range keys {
		if i > 0 {
			b.WriteString("\n")
		}
		fmt.Fprintf(&b, "%s\n    static let %s = %q\n", wrap(e[k].Doc, "    // ", 72), swiftName(k), e[k].Value)
	}
	b.WriteString("}\n")
	return b.String()
}

func renderPython(keys []string, e map[string]entry) string {
	var b strings.Builder
	fmt.Fprintf(&b, "\"\"\"%s\"\"\"\n\n", banner)
	for _, k := range keys {
		fmt.Fprintf(&b, "%s\n%s = %q\n\n", wrap(e[k].Doc, "# ", 76), strings.ToUpper(k), e[k].Value)
	}
	// Trailing blank line trimmed: ruff format rejects it.
	return strings.TrimRight(b.String(), "\n") + "\n"
}
